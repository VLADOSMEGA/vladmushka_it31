-- Завдання 1. printf() для числової колонки
SELECT id, title, copies_count,
       printf('%d прим.', copies_count) AS formatted
FROM books;

-- Результат:
-- 1||5|5 прим.
-- 2|Тигролови|4|4 прим.
-- 3|Захар Беркут|4|4 прим.
-- 4|Лісова пісня|6|6 прим.
-- 5|Місто|2|2 прим.
-- 6|Маленький принц|7|7 прим.
-- 7|Невідома книга|1|1 прим.
-- 8|Книга за замовчуванням|1|1 прим.


-- Завдання 2. printf() з вирівнюванням
SELECT id, title, copies_count,
       printf('%5d', copies_count) AS formatted
FROM books;

-- Результат: числа вирівняні за правим краєм у полі шириною 5 символів.


-- Завдання 3. Зсув дати на 14 днів
SELECT id, issue_date,
       date(issue_date, '+14 days') AS expected_return
FROM loans;

-- Результат:
-- 1|2026-09-01|2026-09-15
-- 2|2026-09-02|2026-09-16
-- 3|2026-09-03|2026-09-17
-- 4|2026-09-04|2026-09-18
-- 5|2026-09-05|2026-09-19
-- 6|2026-09-06|2026-09-20
-- 7|2026-09-07|2026-09-21
-- 8|2026-09-08|2026-09-22
-- 9|2026-09-09|2026-09-23


-- Завдання 4. Групування позик за місяцем
SELECT strftime('%Y-%m', issue_date) AS month,
       COUNT(*) AS loans_count
FROM loans
GROUP BY month;

-- Результат:
-- 2026-09|9


